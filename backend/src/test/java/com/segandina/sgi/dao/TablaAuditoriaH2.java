package com.segandina.sgi.dao;

import jakarta.persistence.EntityManager;

/**
 * Ayuda de pruebas para la tabla {@code auditoria} en H2: la recrea con los tipos que entiende H2 (JSON en vez de
 * JSONB, {@code fecha_hora} con valor por defecto como en la BD real) e inserta registros con fecha fija.
 */
public final class TablaAuditoriaH2 {

	private TablaAuditoriaH2() {
	}

	/**
	 * Reemplaza la tabla que genera Hibernate por una equivalente a la de {@code modelo_datos.sql}.
	 *
	 * @param em entity manager de la prueba
	 */
	public static void recrear(EntityManager em) {
		em.createNativeQuery("DROP TABLE IF EXISTS auditoria").executeUpdate();
		em.createNativeQuery("""
				CREATE TABLE auditoria (
				    id_auditoria     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				    accion_realizada VARCHAR(60) NOT NULL,
				    detalle_cambio   JSON,
				    fecha_hora       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
				    dni_intentado    CHAR(8),
				    id_usuario       BIGINT)
				""").executeUpdate();
	}

	/**
	 * Inserta un registro con fecha fija.
	 *
	 * @param em           entity manager de la prueba
	 * @param accion       valor de {@code accion_realizada}
	 * @param fechaHora    fecha y hora con desfase, p. ej. {@code 2026-10-24 09:00:00-05:00}
	 * @param idUsuario    id del usuario o {@code null}
	 * @param dniIntentado DNI intentado o {@code null}
	 * @param detalleJson  objeto JSON como texto o {@code null}
	 */
	public static void insertar(EntityManager em, String accion, String fechaHora, Long idUsuario,
			String dniIntentado, String detalleJson) {
		em.createNativeQuery("""
				INSERT INTO auditoria (accion_realizada, fecha_hora, id_usuario, dni_intentado, detalle_cambio)
				VALUES (?1, CAST(?2 AS TIMESTAMP WITH TIME ZONE), ?3, ?4, ?5 FORMAT JSON)
				""")
				.setParameter(1, accion)
				.setParameter(2, fechaHora)
				.setParameter(3, idUsuario)
				.setParameter(4, dniIntentado)
				.setParameter(5, detalleJson)
				.executeUpdate();
	}

}
